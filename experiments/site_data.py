"""Turn recorded results into the JSON files the website draws.

Reads `evidence/results/` (restored from the lake with `mb data lake materialize`) and writes `../krn.dev/data/`. Run
`mb run python -m experiments.site_data` from the repository root. Every number on the site comes from a file read here.
"""

import json
import logging
from pathlib import Path

from .paths import RESULTS

SITE = (Path(__file__).resolve().parents[1] / ".." / "krn.dev").resolve()
DATA = SITE / "data"
LOG = logging.getLogger(__name__)

TARGETS = {
    "mac/c": "Mac, C",
    "mac/metal": "Mac, Metal",
    "silo/c": "silo, C",
    "silo/cuda": "RTX 5080, CUDA",
    "crimson/c": "crimson, C",
    "crimson/cuda": "RTX 3090, CUDA",
    "gh200/c": "GH200 Grace, C",
    "gh200/cuda": "GH200 H100, CUDA",
}
GEMM_RUNS = {
    "RTX 5080": ("silo", "sm_120"),
    "RTX 3090": ("crimson", "sm_86"),
}


def load(name: str) -> dict:
    return json.loads((RESULTS / name).read_text())


def conformance() -> dict:
    """Pass counts per target and per family from the conformance run of 2026-11-01."""
    record = load("conformance_20261101.json")
    rows = [
        {
            "target": key,
            "label": label,
            **{k: record["summary"][key]["overall"][k] for k in COUNTS},
            "kernels_of_all": record["summary"][key]["kernels"]["percent_of_all"],
        }
        for key, label in TARGETS.items()
    ]
    families = list(record["summary"]["mac/c"]["by_family"])
    cells = [
        {"target": label, "family": family, **{k: record["summary"][key]["by_family"][family][k] for k in CELL}}
        for key, label in TARGETS.items()
        for family in families
        if family in record["summary"][key]["by_family"]
    ]
    return {"date": record["date"], "rows": rows, "families": families, "cells": cells}


COUNTS = ("applicable", "pass", "partial", "fail", "skip", "percent")
CELL = ("applicable", "pass", "percent")


def best(record: dict) -> float:
    return record["best"]["tflops"] if "best" in record else max(row["tflops"] for row in record["rows"])


def gemm() -> dict:
    """Own tile GEMM against cuBLASLt on the same card, best tile configuration of each recorded run."""
    bars = []
    for card, (host, arch) in GEMM_RUNS.items():
        for dtype in ("f16", "bf16"):
            record = load(f"gemm_gap_{host}_4096_{dtype}.json")
            vendor = record["cublaslt_tflops"]
            bars.append(
                {
                    "card": card,
                    "arch": arch,
                    "dtype": dtype,
                    "krn_tflops": round(best(record), 1),
                    "cublaslt_tflops": round(vendor, 1),
                    "ratio": round(best(record) / vendor, 3),
                }
            )
    library = load("vendor_cublaslt_silo.json")["results"]
    path = next(r for r in library if r["dtype"] == "f16" and r["shape"] == [4096, 4096, 4096])["figures"]
    return {
        "size": 4096,
        "bars": bars,
        "library_path": {"card": "RTX 5080", "dtype": "f16", "ratio": round(path["candidate"]["throughput_ratio"], 4)},
    }


def roadmap() -> None:
    """Export the HTML plan and Markdown entry page independently of site builds."""
    root = Path(__file__).resolve().parents[1]
    document = (root / "ROADMAP.html").read_text()
    destination = SITE / "data" / "library-roadmap.html"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(document)
    page = """---
title: Roadmap
description: Milestones, feature contracts and open decisions for krn.
---

krn aims to make kernels as fast as low-level code and easier to understand, change and verify.
The [expandable library roadmap](/plans/library/) contains milestones, assignable tasks,
open decisions, acceptance cases and primary references.

:::note[Planning is not availability]
Unchecked tasks and proposed APIs are unfinished. Completed history does not certify every
target, dtype or shape. Consult the [support explorer](/targets/compatibility/) for evidence.
:::

Start with [numerics](/language/numerics/), [determinism](/language/determinism/),
[returned arrays](/language/tensors/outputs/) and [testing](/development/testing/).
The [contour solver design](/libraries/contour/) explains a final proof workload.

<!-- Generated by the explicit library export; site builds use only this repository. -->
"""
    (SITE / "src" / "content" / "docs" / "roadmap.md").write_text(page)
    LOG.info("wrote the HTML plan and Markdown entry page")


def main() -> None:
    roadmap()
    DATA.mkdir(parents=True, exist_ok=True)
    for name, build in (("conformance", conformance), ("gemm", gemm)):
        (DATA / f"{name}.json").write_text(json.dumps(build(), indent=2) + "\n")
        LOG.info("wrote %s", DATA / f"{name}.json")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    main()
