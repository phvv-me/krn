"""Generate krn/_ops.py: the fluent tensor and tile methods, from one table of operations.

Every elementwise operation has a pure form (`x.exp()` returns a new value) and an in-place form (`x.exp_()` updates and
returns `x`), the way PyTorch spells them. The same table gives `Tile` (values in registers or shared memory, the
operations fuse into the surrounding kernel) and `Tensor` (host views, the operations are lazy and fuse into one kernel
when the result is first needed). One table means the two classes cannot drift apart, and the same table can later
yield the shape rules and the flops and bytes metadata for profiling.

Run: `python experiments/gen_ops.py` from the sketch directory.
"""

from pathlib import Path

UNARY = {
    "exp": "e^x",
    "exp2": "2^x",
    "exp10": "10^x",
    "expm1": "e^x - 1, accurate near zero",
    "log": "natural logarithm",
    "log2": "base 2 logarithm",
    "log10": "base 10 logarithm",
    "log1p": "log(1 + x), accurate near zero",
    "sqrt": "square root",
    "cbrt": "cube root",
    "rsqrt": "reciprocal square root",
    "reciprocal": "1 / x",
    "sin": "sine",
    "cos": "cosine",
    "tanh": "hyperbolic tangent",
    "sigmoid": "1 / (1 + e^-x)",
    "erf": "error function",
    "floor": "round toward minus infinity",
    "ceil": "round toward plus infinity",
    "round": "round half to even",
    "trunc": "round toward zero",
    "relu": "max(x, 0)",
    "gelu": "x * Phi(x), the exact Gaussian form",
    "silu": "x * sigmoid(x)",
    "softplus": "log(1 + e^x)",
    "abs": "absolute value",
}
BINARY = {
    "add": "x + other",
    "sub": "x - other",
    "mul": "x * other",
    "div": "x / other",
    "maximum": "elementwise maximum; a NaN propagates, as in numpy and torch",
    "minimum": "elementwise minimum; a NaN propagates, as in numpy and torch",
    "pow": "x ** other",
}
REDUCTIONS = {
    "sum": "sum over an axis",
    "prod": "product over an axis",
    "mean": "mean of the valid lanes over an axis; a lane with none is NaN, as numpy gives, and is stored",
    "max": "largest over an axis",
    "min": "smallest over an axis",
    "logsumexp": "log(sum(e^x)) over an axis, computed stably",
    "norm": "Euclidean norm over an axis",
}
NORMALIZING = {
    "softmax": "e^x / sum(e^x) over an axis, computed stably; the shape is unchanged",
    "log_softmax": "x - logsumexp(x) over an axis, computed stably; the shape is unchanged",
}

CLASSES = {
    "TileOps": ("Tile", "A tile in registers or shared memory. Operations fuse into the surrounding kernel."),
    "TensorOps": ("Tensor", "A host tensor. Operations are lazy and fuse into one kernel when the result is needed."),
}


def methods(kind: str) -> list[str]:
    out: list[str] = []
    for name, doc in UNARY.items():
        out.append(f'    def {name}(self) -> {kind}[T, *Shape]:\n        """{doc}"""\n        return todo()\n')
        out.append(
            f'    def {name}_(self) -> {kind}[T, *Shape]:\n        """In place: {doc}"""\n        return todo()\n'
        )
    for name, doc in BINARY.items():
        out.append(
            f"    def {name}[*S](self, other: {kind}[T, *S] | T | float) -> {kind}[T, *Shape]:\n"
            f'        """{doc}"""\n        return todo()\n'
        )
        out.append(
            f"    def {name}_[*S](self, other: {kind}[T, *S] | T | float) -> {kind}[T, *Shape]:\n"
            f'        """In place: {doc}"""\n        return todo()\n'
        )
    out.append(
        f"    def clip(self, low: T | float, high: T | float) -> {kind}[T, *Shape]:\n"
        f'        """Limit every element to [low, high]."""\n        return todo()\n'
    )
    out.append(
        f"    def clip_(self, low: T | float, high: T | float) -> {kind}[T, *Shape]:\n"
        f'        """In place: limit every element to [low, high]."""\n        return todo()\n'
    )
    operand = f"{kind}[T, *Shape] | T | float"
    for suffix, prefix in (("", ""), ("_", "In place: ")):
        out.append(
            f"    def fma{suffix}(self, b: {operand}, c: {operand}) -> {kind}[T, *Shape]:\n"
            f'        """{prefix}x * b + c with one rounding"""\n        return todo()\n'
        )
    for name, doc in NORMALIZING.items():
        out.append(
            f'    def {name}(self, axis: int = -1) -> {kind}[T, *Shape]:\n        """{doc}"""\n        return todo()\n'
        )
    for name, doc in REDUCTIONS.items():
        out.append(
            f"    def {name}(self, axis: int = -1, *, keepdims: bool = False) -> {kind}[T, *tuple[int, ...]]:\n"
            f'        """{doc}"""\n        return todo()\n'
        )
    return out


def render() -> str:
    head = (
        '"""Fluent operations of tiles and tensors. Generated by experiments/gen_ops.py: do not edit."""\n\n'
        "from typing import TYPE_CHECKING, Generic, TypeVar, TypeVarTuple\n\n"
        "from .numerics import Scalar, todo\n\n"
        "if TYPE_CHECKING:\n    from .memory import Tensor, Tile\n\n"
        'T = TypeVar("T", bound=Scalar | bool)\nShape = TypeVarTuple("Shape")\n'
    )
    body = []
    for name, (kind, doc) in CLASSES.items():
        body.append(f'\n\nclass {name}(Generic[T, *Shape]):\n    """{doc}"""\n\n' + "\n".join(methods(kind)))
    return head + "".join(body)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "src" / "krn" / "frontend" / "_ops.py"
    target.write_text(render())
